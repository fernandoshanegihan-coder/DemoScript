/** Server-side Azure Speech adapter. Never import this module from a client component. */
export class SpeechError extends Error {
  status: number;
  constructor(message: string, status = 502) { super(message); this.status = status; }
}

export const SPEECH_VOICES = ["en-US-JennyNeural", "en-US-GuyNeural", "en-GB-SoniaNeural"] as const;
export type SpeechVoice = typeof SPEECH_VOICES[number];

function escapeXml(text: string): string {
  return text.replace(/[&<>"']/g, value => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&apos;" })[value]!);
}

export function speechMarkup(text: string, voice: SpeechVoice, speed = 1): string {
  const locale = voice.startsWith("en-GB") ? "en-GB" : "en-US";
  return `<speak version="1.0" xmlns="http://www.w3.org/2001/10/synthesis" xml:lang="${locale}"><voice name="${voice}"><prosody rate="${Math.round((speed - 1) * 100)}%">${escapeXml(text)}</prosody></voice></speak>`;
}

/** Read the actual PCM duration, including any silence generated by the service. */
export function speechWavSeconds(bytes: Uint8Array): number {
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  const tag = (offset: number) => String.fromCharCode(...bytes.subarray(offset, offset + 4));
  if (bytes.length < 44 || tag(0) !== "RIFF" || tag(8) !== "WAVE") throw new SpeechError("The voice service returned unreadable audio. Your existing takes are kept.");
  let byteRate = 0, dataBytes = 0;
  for (let offset = 12; offset + 8 <= bytes.length;) {
    const size = view.getUint32(offset + 4, true);
    if (offset + 8 + size > bytes.length) throw new SpeechError("The voice audio was incomplete. Please try again.");
    if (tag(offset) === "fmt " && size >= 16) byteRate = view.getUint32(offset + 16, true);
    if (tag(offset) === "data") dataBytes += size;
    offset += 8 + size + (size % 2);
  }
  const seconds = dataBytes / byteRate;
  if (!Number.isFinite(seconds) || seconds <= 0) throw new SpeechError("The voice service returned empty audio. Please try again.");
  return seconds;
}

/** Adjust the synthesizer's speaking rate; never crop the words or alter the video. */
export async function fitSpeech(
  seconds: number,
  synthesize: (speed: number) => Promise<Uint8Array>,
): Promise<{ audio: Uint8Array; seconds: number }> {
  let speed = 1;
  for (let attempt = 0; attempt < 3; attempt++) {
    const audio = await synthesize(speed);
    const duration = speechWavSeconds(audio);
    if (duration <= seconds && (duration >= seconds * .75 || attempt === 2)) return { audio, seconds: duration };
    const adjusted = Math.max(.75, Math.min(1.35, speed * duration / (seconds * .92)));
    if (Math.abs(adjusted - speed) < .01) {
      if (duration <= seconds) return { audio, seconds: duration };
      break;
    }
    speed = adjusted;
  }
  throw new SpeechError("This scene needs more speaking time. Shorten its script or record your own voice. Existing takes are kept.", 422);
}

let dailyUsage = { day: "", characters: 0 };
let active = false;

export async function generateSpeech(text: string, seconds: number, voice: SpeechVoice, signal?: AbortSignal) {
  const key = process.env.AZURE_SPEECH_KEY?.trim();
  const region = process.env.AZURE_SPEECH_REGION?.trim();
  if (!key || !region) throw new SpeechError("Automatic voice isn't configured yet. Add the Azure Speech key and region to the server settings, then restart.", 503);
  if (!/^[a-z]+[a-z0-9]*$/.test(region)) throw new SpeechError("Check the Azure Speech region in the server settings, such as centralindia.", 503);
  if (active) throw new SpeechError("The voice service is working on another scene. Please try again shortly.", 429);
  const day = new Date().toISOString().slice(0, 10);
  if (dailyUsage.day !== day) dailyUsage = { day, characters: 0 };
  const configured = Number(process.env.AZURE_SPEECH_DAILY_CHAR_LIMIT || 10000);
  const dailyLimit = Number.isFinite(configured) && configured > 0 ? configured : 10000;
  active = true;
  try {
    return await fitSpeech(seconds, async speed => {
      signal?.throwIfAborted();
      if (dailyUsage.characters + text.length > dailyLimit) throw new SpeechError("Today's automatic voice allowance is used up. You can still record your own narration.", 429);
      dailyUsage.characters += text.length;
      const response = await fetch(`https://${region}.tts.speech.microsoft.com/cognitiveservices/v1`, {
        method: "POST", signal: signal ? AbortSignal.any([signal, AbortSignal.timeout(40000)]) : AbortSignal.timeout(40000),
        headers: { "Ocp-Apim-Subscription-Key": key, "Content-Type": "application/ssml+xml", "X-Microsoft-OutputFormat": "riff-24khz-16bit-mono-pcm", "User-Agent": "DemoScript" },
        body: speechMarkup(text, voice, speed),
      });
      if (!response.ok) {
        // Azure response bodies can contain account details. Never forward or log them.
        if (response.status === 401 || response.status === 403) throw new SpeechError("Azure rejected the Speech credentials. Check that the key and region belong to the same Speech resource.", 503);
        if (response.status === 429) throw new SpeechError("Azure's voice limit was reached. Wait a moment before trying again, or record your own voice.", 429);
        throw new SpeechError("The voice service could not create this scene. Your existing takes are kept.");
      }
      return new Uint8Array(await response.arrayBuffer());
    });
  } finally { active = false; }
}
